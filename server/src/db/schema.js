/* Schema migrations for Postgres, applied in order; the number of applied steps is kept in schema_migrations (see db/index.js).
   Applied migrations are never edited: a change is a new entry at the end.

   Conventions: amounts are TEXT holding decimal wei (see util/amounts.js), never numeric columns, so no rounding can ever
   happen in the database. Timestamps are epoch milliseconds in BIGINT. Flags are INTEGER 0/1.

   Step 1 is the whole schema as the SQLite version of this server left it after its seven migrations (users with optional
   wallet address + email accounts, invite lobbies, minimum deposits, withdrawal fees). Moving to Postgres started from an
   empty database, so none of that history needs replaying. */
export const MIGRATIONS = [
  /* 1 — initial Postgres schema */
  `
  CREATE TABLE users (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address               TEXT UNIQUE,                        -- lowercase 0x…, the linked wallet (NULL for an email account without one)
    display_name          TEXT    NOT NULL,
    created_at            BIGINT  NOT NULL,
    loss_limit            TEXT,                               -- daily loss limit in wei, NULL = off
    loss_limit_pending    TEXT,                               -- a loosening that has not taken effect yet: wei, or 'off'
    loss_limit_pending_at BIGINT,
    strikes               INTEGER NOT NULL DEFAULT 0,         -- no-shows
    last_strike_at        BIGINT  NOT NULL DEFAULT 0,
    queue_ban_until       BIGINT  NOT NULL DEFAULT 0,
    banned                INTEGER NOT NULL DEFAULT 0,
    age_attested_at       BIGINT,                             -- 18+ attestation, required before any staked action
    email                 TEXT UNIQUE,                        -- lowercase
    email_verified_at     BIGINT,
    password_hash         TEXT                                -- "scrypt$N$r$p$salt$hash" (base64url)
  );

  CREATE TABLE auth_nonces (
    nonce      TEXT PRIMARY KEY,                              -- keyed by nonce (not address) so nobody can burn another wallet's pending sign-in
    address    TEXT   NOT NULL,
    message    TEXT   NOT NULL,
    expires_at BIGINT NOT NULL
  );
  CREATE INDEX auth_nonces_address ON auth_nonces(address);

  CREATE TABLE sessions (
    token_hash TEXT PRIMARY KEY,                              -- sha256 of the bearer token; the token itself is never stored
    seq        BIGINT GENERATED ALWAYS AS IDENTITY,           -- creation order, to keep the newest sessions of a user
    user_id    BIGINT NOT NULL REFERENCES users(id),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    ip         TEXT
  );
  CREATE INDEX sessions_user ON sessions(user_id);

  CREATE TABLE email_tokens (
    token_hash TEXT PRIMARY KEY,                              -- sha256 of the one-time link token
    user_id    BIGINT NOT NULL REFERENCES users(id),
    kind       TEXT   NOT NULL,                               -- 'verify' | 'reset'
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
  );
  CREATE INDEX email_tokens_user ON email_tokens(user_id, kind);

  CREATE TABLE deposit_addresses (
    user_id     BIGINT PRIMARY KEY REFERENCES users(id),
    idx         BIGINT  NOT NULL UNIQUE,                      -- HD derivation index
    address     TEXT    NOT NULL UNIQUE,                      -- lowercase
    needs_sweep INTEGER NOT NULL DEFAULT 0,
    created_at  BIGINT  NOT NULL
  );

  /* ---- double-entry ledger ---- */
  CREATE TABLE accounts (
    id      TEXT PRIMARY KEY,                                 -- user:7 | escrow:ticket:3 | escrow:match:9 | escrow:withdrawal:2 | house:fees | external:chain
    kind    TEXT NOT NULL,
    balance TEXT NOT NULL DEFAULT '0'
  );
  CREATE TABLE ledger_tx (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind       TEXT   NOT NULL,
    ref        TEXT,
    uniq       TEXT UNIQUE,                                   -- idempotency key: a second insert with the same key is refused
    memo       TEXT,
    created_at BIGINT NOT NULL
  );
  CREATE TABLE ledger_entries (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tx_id   BIGINT NOT NULL REFERENCES ledger_tx(id),
    account TEXT   NOT NULL REFERENCES accounts(id),
    amount  TEXT   NOT NULL                                   -- signed; every tx sums to 0
  );
  CREATE INDEX entries_account ON ledger_entries(account, id);
  CREATE INDEX entries_tx      ON ledger_entries(tx_id);

  /* ---- chain plumbing ---- */
  CREATE TABLE chain_state (key TEXT PRIMARY KEY, value TEXT NOT NULL);

  CREATE TABLE deposits (
    tx_hash      TEXT PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id),
    address      TEXT   NOT NULL,
    amount       TEXT   NOT NULL,
    block_number BIGINT NOT NULL,
    credited_at  BIGINT NOT NULL,                             -- 0 while pending
    status       TEXT   NOT NULL DEFAULT 'credited',          -- credited | pending (below the minimum deposit so far)
    detected_at  BIGINT
  );
  CREATE INDEX deposits_user ON deposits(user_id, credited_at);
  CREATE INDEX deposits_pending ON deposits(address) WHERE status = 'pending';

  CREATE TABLE sweeps (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id),
    address    TEXT   NOT NULL,
    amount     TEXT   NOT NULL,                               -- value sent to the treasury
    tx_hash    TEXT   NOT NULL,
    raw_tx     TEXT   NOT NULL,
    status     TEXT   NOT NULL,                               -- pending | confirmed | failed
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
  );
  CREATE INDEX sweeps_status ON sweeps(status);

  CREATE TABLE withdrawals (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id),
    to_address   TEXT   NOT NULL,
    amount       TEXT   NOT NULL,
    fee          TEXT   NOT NULL DEFAULT '0',                 -- network fee charged on top of amount (ledger: user → house:gas)
    status       TEXT   NOT NULL,                             -- queued | signed | broadcast | confirmed | failed
    idem_key     TEXT,
    nonce        BIGINT,
    tx_hash      TEXT,
    raw_tx       TEXT,
    block_number BIGINT,
    error        TEXT,
    created_at   BIGINT NOT NULL,
    updated_at   BIGINT NOT NULL,
    broadcast_at BIGINT,
    UNIQUE (user_id, idem_key)
  );
  CREATE INDEX withdrawals_status ON withdrawals(status, id);

  /* ---- games ---- */
  CREATE TABLE tickets (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT  NOT NULL REFERENCES users(id),
    game            TEXT    NOT NULL,
    stake           TEXT    NOT NULL,
    code            TEXT,                                     -- the lobby's invite code (host and guests)
    rating          INTEGER NOT NULL,
    state           TEXT    NOT NULL,                         -- queued (waiting in an open lobby) | matched | cancelled | expired | left
    created_at      BIGINT  NOT NULL,
    closed_at       BIGINT,
    match_id        BIGINT,
    lobby_code      TEXT,                                     -- set on the host's ticket only
    lobby_ticket_id BIGINT                                    -- a guest's ticket → the host's ticket
  );
  CREATE INDEX tickets_state ON tickets(state);
  CREATE UNIQUE INDEX tickets_lobby_code ON tickets(lobby_code) WHERE lobby_code IS NOT NULL;
  CREATE INDEX tickets_lobby_ticket ON tickets(lobby_ticket_id) WHERE lobby_ticket_id IS NOT NULL;

  CREATE TABLE matches (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game            TEXT   NOT NULL,
    stake           TEXT   NOT NULL,                          -- per player
    pot             TEXT   NOT NULL,
    fee             TEXT   NOT NULL DEFAULT '0',
    state           TEXT   NOT NULL,                          -- found | playing | settled | void
    outcome         TEXT,                                     -- win | draw | void
    reason          TEXT,                                     -- scores | forfeit | timeout | no_show | no_result | ...
    seed            BIGINT,
    code            TEXT,
    created_at      BIGINT NOT NULL,
    ready_deadline  BIGINT,
    start_at        BIGINT,
    submit_deadline BIGINT,
    settled_at      BIGINT,
    winner_seat     INTEGER
  );
  CREATE INDEX matches_state ON matches(state);

  CREATE TABLE match_players (
    match_id      BIGINT  NOT NULL REFERENCES matches(id),
    seat          INTEGER NOT NULL,                           -- 0..9, in join order (a lobby host is seat 0)
    user_id       BIGINT  NOT NULL REFERENCES users(id),
    ticket_id     BIGINT,
    rating_before INTEGER NOT NULL,
    rating_after  INTEGER,
    ready_at      BIGINT,
    seed_sent     INTEGER NOT NULL DEFAULT 0,
    score         DOUBLE PRECISION,
    detail        TEXT,
    submitted_at  BIGINT,
    forfeited     INTEGER NOT NULL DEFAULT 0,
    payout        TEXT,
    flag          TEXT,                                       -- set when the score looks implausible (reviewed by an operator)
    PRIMARY KEY (match_id, seat)
  );
  CREATE INDEX match_players_user ON match_players(user_id, match_id);

  CREATE TABLE ratings (
    user_id    BIGINT  NOT NULL REFERENCES users(id),
    game       TEXT    NOT NULL,
    rating     INTEGER NOT NULL DEFAULT 1200,
    wins       INTEGER NOT NULL DEFAULT 0,
    losses     INTEGER NOT NULL DEFAULT 0,
    draws      INTEGER NOT NULL DEFAULT 0,
    best       DOUBLE PRECISION,
    updated_at BIGINT  NOT NULL,
    PRIMARY KEY (user_id, game)
  );
  CREATE INDEX ratings_board ON ratings(game, rating DESC);

  CREATE TABLE player_day (
    user_id BIGINT NOT NULL REFERENCES users(id),
    day     TEXT   NOT NULL,                                  -- UTC yyyy-mm-dd
    net     TEXT   NOT NULL DEFAULT '0',                      -- signed wei: payouts minus stakes for settled staked matches
    PRIMARY KEY (user_id, day)
  );

  /* Supabase serves every table in its public schema through its REST API to anyone holding the project's anon key.
     Row level security with no policies shuts that door: the API roles see and change nothing. The server connects as the
     tables' owner, which RLS does not apply to, so it is unaffected. Harmless on a plain Postgres. */
  DO $$
  DECLARE t record;
  BEGIN
    FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = current_schema() LOOP
      EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t.tablename);
    END LOOP;
  END $$;
  `,

  /* 2 — Supabase Auth: the Supabase user id of an email account (src/supabaseAuth.js) */
  `
  ALTER TABLE users ADD COLUMN auth_id TEXT UNIQUE;
  `,
];
